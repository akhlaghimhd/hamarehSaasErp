/**
 * Enriches tenant_permissions.description with operational Persian text
 * so role-assign UI shows what granting/denying each permission actually does.
 * Safe to re-run. Only overwrites weak descriptions (empty / same as name / < 40 chars).
 * Persian names are updated only when the existing name still contains Latin letters.
 */
class EnrichPermissionDescriptionsSeeder extends Seeder
{
    public function run(): void
    {
        if (! Schema::hasTable('tenant_permissions')) {
            return;
        }

        $catalog = $this->opsCatalog();
        $nameCatalog = $this->nameCatalog();

        foreach ($catalog as $code => $description) {
            $rows = DB::table('tenant_permissions')
                ->where('code', $code)
                ->get(['tenant_permission_id', 'name', 'description']);

            foreach ($rows as $row) {
                $currentDesc = trim((string) ($row->description ?? ''));
                $currentName = trim((string) ($row->name ?? ''));

                // Only enrich weak descriptions: empty, same as title, or too short.
                // Owner/admin long custom text is preserved.
                $weakDesc = $currentDesc === ''
                    || $currentDesc === $currentName
                    || mb_strlen($currentDesc) < 40;

                $payload = ['updated_at' => now()];
                $dirty = false;

                if ($weakDesc) {
                    $payload['description'] = $description;
                    $dirty = true;
                }

                // Name: only replace if still has Latin (technical leftover).
                if (
                    isset($nameCatalog[$code])
                    && $currentName !== ''
                    && preg_match('/[A-Za-z]{2,}/u', $currentName)
                ) {
                    $payload['name'] = $nameCatalog[$code];
                    $dirty = true;
                }

                if ($dirty) {
                    DB::table('tenant_permissions')
                        ->where('tenant_permission_id', $row->tenant_permission_id)
                        ->update($payload);
                }
            }
        }
    }

